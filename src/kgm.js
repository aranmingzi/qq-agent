// 酷狗 KGM / KGMA 加密音频解密。
//
// 为什么需要它：群友从酷狗下歌，发过来的是 `侧脸.kgm.flac` ——
// 扩展名写着 flac，内容其实是 KGM 加密流（头 16 字节 `7cd532eb86027f4b…`）。
// ffmpeg 直接读会报 "Output file #0 does not contain any stream"，
// 翻唱作业在 5% 就失败，群里看起来就是「发了歌却唱不了」。
//
// 算法与 unlock-music（MIT）的 KgmWasm 一致，逐字节：
//   med8 = key[i%17] ^ raw;  med8 ^= (med8 & 0xf) << 4;
//   msk8 = predef[i%272] ^ maskValue(i>>4);  msk8 ^= (msk8 & 0xf) << 4;
//   out = med8 ^ msk8
//
// ★ 关于 maskValue：老版本 unlock-music 用的是一张 4 MiB 的 `kgm.mask` 静态表
//   （查表 pos>>4），只覆盖前 64 MiB 密文 —— 超过就解不动，81 MB 的歌只能保住前 3 分钟。
//   新版 WASM 改成用 table1/table2 做位移递推：
//     offset = pos>>4;  while (offset >= 0x11) { v ^= t1[offset%272]; offset>>=4;
//                                                 v ^= t2[offset%272]; offset>>=4; }
//   它没有表长上限，8 万次位移后仍在合理范围，因此**整首歌都能解开**。
//   实测 81 MB / 3:37 的 96kHz 24bit flac：全曲解码零错误。

