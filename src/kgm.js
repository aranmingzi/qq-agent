/** 是不是酷狗加密音频（KGM / VPR）。扩展名不可信，只认魔数。 */
export function isKgm(buf) {
  if (!buf || buf.length < 0x400) return false;
  return buf.subarray(0, 16).equals(KGM_MAGIC) || buf.subarray(0, 16).equals(VPR_MAGIC);
}

/** 是不是 VPR（酷狗 VIP 的另一种封装，解密后要多异或一层）。 */
function isVpr(buf) {
  return buf.subarray(0, 16).equals(VPR_MAGIC);
}

/** 只读文件头判断，不把 80MB 的密文整个吞进内存。 */
export function isKgmFile(file) {
  try {
    const fd = fs.openSync(file, 'r');
    try {
      const head = Buffer.alloc(16);
      if (fs.readSync(fd, head, 0, 16, 0) < 16) return false;
      return head.equals(KGM_MAGIC) || head.equals(VPR_MAGIC);
    } finally {
      fs.closeSync(fd);
    }
  } catch {
    return false;
  }
}

/**
 * mask 的高位部分：只依赖 `pos >> 4`，同一个 16 字节块内是常数。
 * 单独抽出来是为了让主循环能按块复用，少算 16 倍 —— 81 MB 的歌差好几百毫秒。
 */
function maskValueOf(offset, t1, t2) {
  let v = 0;
  let o = offset;
  while (o >= 0x11) {
    v ^= t1[o % 272];
    o >>>= 4;
    v ^= t2[o % 272];
    o >>>= 4;
  }
  return v;
}

/**
 * 解密成明文音频（flac）。整首歌一次解完，没有长度上限。
 * @param {Buffer} buf KGM 密文
 * @param {object} [tables] 仅供自检注入零表用，生产路径不要传
 * @returns {{buffer: Buffer, headerLen: number, encryptedBytes: number}}
 */
export function decryptKgmSync(buf, tables = null) {
  const predef = tables?.predef || MASK_PREDEF;
  const t1 = tables?.t1 || MASK_TABLE1;
  const t2 = tables?.t2 || MASK_TABLE2;
  const headerLen = buf.readUInt32LE(0x10);
  if (!Number.isFinite(headerLen) || headerLen < 0x10 || headerLen >= buf.length) {
    throw new Error('KGM 文件头异常，解不了（headerLen=' + headerLen + '）');
  }
  const vpr = isVpr(buf);
  const key = Buffer.alloc(17);
  buf.copy(key, 0, 0x1c, 0x2c);            // 第 17 字节保持 0，算法就这么设计的
  const n = buf.length - headerLen;
  const out = Buffer.allocUnsafe(n);
  for (let base = 0; base < n; base += 16) {
    const mV = maskValueOf(base >> 4, t1, t2);
    const end = Math.min(base + 16, n);
    for (let i = base; i < end; i++) {
      let med8 = key[i % 17] ^ buf[headerLen + i];
      med8 ^= (med8 & 0xf) << 4;
      let msk8 = predef[i % 272] ^ mV;
      msk8 ^= (msk8 & 0xf) << 4;
      out[i] = med8 ^ msk8;
    }
  }
  if (vpr) {
    for (let i = 0; i < n; i++) out[i] ^= VPR_MASK_DIFF[i % 17];
  }
  return { buffer: out, headerLen, encryptedBytes: n };
}

/**
 * 把 KGM 密文变成「能直接喂给翻唱链路」的本地音频文件。
 *
 * 正常情况下解密结果就是完整的 flac，直接落盘（零损失、不重编码）。
 * 只有解出来发现坏帧（极少数新变种）才会退化成 ffmpeg 容错解码 → wav，
 * 把解不动的尾巴切掉，至少保证能唱。
 *
 * @param {Buffer} buf  原始密文
 * @param {object} opts
 * @param {string} opts.stem  输出文件名（不带扩展名）
 * @param {string} opts.dir   输出目录
 * @param {function} [opts.log]
 * @returns {Promise<{file: string, seconds: number|null, truncated: boolean, fullSeconds: number|null}>}
 */
export async function decryptKgmToAudio(buf, { stem = '酷狗解密', dir, log = null } = {}) {
  const outDir = dir || path.join(ROOT, 'cache', 'incoming');
  fs.mkdirSync(outDir, { recursive: true });

  const dec = decryptKgmSync(buf);
  if (dec.buffer.subarray(0, 4).toString('ascii') !== 'fLaC') {
    throw new Error('KGM 解密结果不是 flac（可能是不支持的新版本加密），让群友发未加密的音频吧');
  }
  const flac = path.join(outDir, `${stem}.flac`);
  fs.writeFileSync(flac, dec.buffer);

  const ff = resolveFfmpeg();
  if (!ff) return { file: flac, seconds: null, truncated: false, fullSeconds: null };

  // 全量试解码：flac 每帧自带 CRC，解一遍就能确认整首歌没有烂帧。
  const check = await runProc(ff, ['-hide_banner', '-v', 'error', '-i', flac, '-f', 'null', '-'], { timeoutMs: 300000 });
  const clean = !String(check.stderr || '').trim();
  const fullSeconds = await probeSeconds(ff, flac).catch(() => null);

  if (clean) {
    if (log) log(`[KGM] 解密完成：${fmtSec(fullSeconds)}，整曲无损`);
    return { file: flac, seconds: fullSeconds, truncated: false, fullSeconds };
  }

  // 有坏帧 → 容错解码，能解多少算多少（-err_detect ignore_err 让 ffmpeg 跳过坏帧继续）
  if (log) log('[KGM] 解密结果有坏帧，改用容错解码截取可解部分…');
  const wav = path.join(outDir, `${stem}.wav`);
  const r = await runProc(ff, [
    '-hide_banner', '-v', 'error', '-err_detect', 'ignore_err', '-y',
    '-i', flac, '-ar', '44100', '-ac', '2', '-c:a', 'pcm_s16le', wav,
  ], { timeoutMs: 600000 });
  if (!fs.existsSync(wav) || fs.statSync(wav).size < 1024) {
    try { fs.unlinkSync(wav); } catch { /* 没生成就不用删 */ }
    throw new Error('KGM 解密后转码失败：' + String(r.stderr || '').split('\n').slice(-2).join(' ').slice(0, 200));
  }
  try { fs.unlinkSync(flac); } catch { /* 留着也无害，但别占 80MB */ }
  const seconds = Math.round((fs.statSync(wav).size - 44) / (44100 * 2 * 2) * 10) / 10;
  const truncated = !!fullSeconds && seconds < fullSeconds - 3;
  if (log) {
    log(`[KGM] 解密完成：${fmtSec(seconds)}${truncated ? `（原曲 ${fmtSec(fullSeconds)}，坏帧之后的部分已切掉）` : ''}`);
  }
  return { file: wav, seconds, truncated, fullSeconds };
}

function fmtSec(s) {
  if (!s) return '未知时长';
  const m = Math.floor(s / 60);
  const r = Math.round(s % 60);
  return `${m}:${String(r).padStart(2, '0')}`;
}

/** ffprobe 不一定装，用 ffmpeg 读文件头里的 Duration 兜底。 */
async function probeSeconds(ff, file) {
  const r = await runProc(ff, ['-hide_banner', '-i', file], { timeoutMs: 60000 });
  const m = String(r.stderr || '').match(/Duration:\s*(\d+):(\d+):(\d+\.\d+)/);
  if (!m) return null;
  return Number(m[1]) * 3600 + Number(m[2]) * 60 + Number(m[3]);
}
